INPUT_KEYS = [k for _s, fields in INPUT_SECTIONS for k, _l, _h in fields]


def _div(n, d):
    return n / d if d else None


def compute(inp: dict) -> dict:
    """All calculated subtotals, ratios, and composite scores for one period's inputs."""
    g = lambda k: float(inp.get(k) or 0)
    cash, ar, invtry, oca = g("cash"), g("accounts_receivable"), g("inventory"), g("other_current_assets")
    nca, ap, std, ocl, ltd = (g("non_current_assets"), g("accounts_payable"), g("short_term_debt"),
                              g("other_current_liabilities"), g("long_term_debt"))
    rev, cogs, opex, dep, intexp, taxexp = (g("revenue"), g("cogs"), g("operating_expenses"),
                                            g("depreciation"), g("interest_expense"), g("tax_expense"))
    ocf, capex, tds, topex, fin = (g("operating_cash_flow"), g("capex"), g("total_debt_service"),
                                   g("total_operating_expenses"), g("financing_inflows"))
    burn, dro, dpo, dio = (g("monthly_cash_burn"), g("days_receivable"),
                           g("days_payable"), g("days_inventory"))

    tca = cash + ar + invtry + oca
    ta = tca + nca
    tcl = ap + std + ocl
    tl = tcl + ltd
    eq = ta - tl
    gp = rev - cogs
    ebit = gp - opex - dep
    ni = ebit - intexp - taxexp
    fcf = ocf - capex
    debt = std + ltd

    calc = {
        "total_current_assets": round(tca, 2), "total_assets": round(ta, 2),
        "total_current_liabilities": round(tcl, 2), "total_liabilities": round(tl, 2),
        "total_equity": round(eq, 2), "gross_profit": round(gp, 2), "ebit": round(ebit, 2),
        "net_income": round(ni, 2), "free_cash_flow": round(fcf, 2),
    }

    def R(category, name, value, benchmark, interp):
        return {"category": category, "name": name,
                "value": (round(value, 4) if isinstance(value, float) else value),
                "benchmark": benchmark, "interpretation": interp}

    ratios = [
        R("Solvency", "Debt-to-Equity", _div(debt, eq), "< 2.0x", "Total debt ÷ equity. Lower = less leveraged"),
        R("Solvency", "Debt-to-Assets", _div(debt, ta), "< 50%", "How much of total assets is financed by debt"),
        R("Solvency", "Interest Coverage", _div(ebit, intexp), "> 3.0x", "EBIT ÷ interest. Can it cover interest from operations?"),
        R("Solvency", "Equity Ratio", _div(eq, ta), "> 50%", "Equity ÷ total assets. Higher = more self-financed"),
        R("Liquidity", "Current Ratio", _div(tca, tcl), "> 1.5x", "Current assets ÷ current liabilities"),
        R("Liquidity", "Quick Ratio", _div(cash + ar, tcl), "> 1.0x", "(Cash + receivables) ÷ current liabilities"),
        R("Liquidity", "Working Capital", round(tca - tcl, 2), "> $0", "Current assets − current liabilities"),
        R("Profitability", "Gross Margin", _div(gp, rev), "> 30%", "Gross profit ÷ revenue"),
        R("Profitability", "Operating Margin", _div(ebit, rev), "> 10%", "EBIT ÷ revenue"),
        R("Profitability", "Net Margin", _div(ni, rev), "> 5%", "Net income ÷ revenue"),
        R("Profitability", "Return on Assets (ROA)", _div(ni, ta), "> 5%", "Net income ÷ total assets"),
        R("Profitability", "Return on Equity (ROE)", _div(ni, eq), "> 10%", "Net income ÷ equity"),
        R("Cash Sustainability", "OCF vs Net Income", _div(ocf, ni), "> 1.0x", "Operating cash flow ÷ net income"),
        R("Cash Sustainability", "Free Cash Flow", round(fcf, 2), "> $0", "OCF − CapEx"),
        R("Cash Sustainability", "Cash Burn (monthly)", burn or None, "Context", "Net monthly cash outflow"),
        R("Cash Sustainability", "Cash Runway (months)", _div(cash, burn), "> 12 mo", "Cash ÷ monthly burn"),
        R("Leverage / Risk", "Debt Service Burden", _div(tds, ocf), "< 40%", "Debt service ÷ operating cash flow"),
        R("Leverage / Risk", "Debt-to-EBITDA", _div(debt, ebit + dep), "< 3.0x", "Total debt ÷ EBITDA"),
        R("Leverage / Risk", "Financing Reliance", _div(fin, ocf + fin), "< 25%", "Financing inflows ÷ (OCF + financing)"),
        R("Efficiency", "Asset Turnover", _div(rev, ta), "> 0.5x", "Revenue ÷ total assets"),
        R("Efficiency", "Receivables / Payables Timing", (dro - dpo) if dpo else None, "< 0 days", "Days receivable − days payable"),
        R("Efficiency", "Inventory Turnover (days)", dio or None, "Context", "Days inventory outstanding"),
    ]

    # --- composite 0–100 scores (exact workbook formulas; cap at 100, may go negative) ---
    def _cap(x):
        return min(100, round(x))

    def resilience():
        if ta == 0 or tcl == 0 or eq == 0:
            return None
        t1 = (min(tca / tcl, 3) / 3 if tcl > 0 else 0) * 25
        t2 = (min(debt / eq, 4) if eq > 0 else 4) / 4 * 25
        t3 = (min(ebit / intexp, 6) / 6 if intexp > 0 else 0) * 25
        t4 = (min(eq / ta, 1) if ta > 0 else 0) * 25
        return _cap(t1 + t2 + t3 + t4)

    def fragility():
        if ta == 0 or tcl == 0:
            return None
        t1 = ((1 - min(tca / tcl, 2) / 2) if tcl > 0 else 1) * 30
        t2 = (min(debt / ta, 1) if ta > 0 else 0) * 30
        t3 = (min(tds / ocf, 1) if ocf > 0 else 0) * 20
        t4 = ((1 - min(cash / tcl, 1)) if cash > 0 else 1) * 20
        return _cap(t1 + t2 + t3 + t4)

    def self_fund():
        if rev == 0 or ta == 0:
            return None
        t1 = (min(fcf / rev, 0.3) / 0.3 if rev > 0 else 0) * 35
        t2 = (min(ni / rev, 0.2) / 0.2 if rev > 0 else 0) * 30
        t3 = (min(ni / ta, 0.15) / 0.15 if ta > 0 else 0) * 35
        return _cap(t1 + t2 + t3)

    def dependence():
        if ocf == 0 or rev == 0:
            return None
        t1 = (min(fin / (ocf + fin), 1) if (ocf + fin) > 0 else 0) * 40
        t2 = (min(debt / ta, 1) if ta > 0 else 0) * 30
        t3 = 30 if fcf < 0 else (15 if fcf < capex * 0.1 else 0)
        return _cap(t1 + t2 + t3)

    def earnings_quality():
        if ni == 0 or rev == 0:
            return None
        t1 = (min(ocf / ni, 2) / 2 if ni != 0 else 0) * 50
        t2 = (min(ni / rev, 0.2) / 0.2 if rev > 0 else 0) * 25
        t3 = 25 if fcf > 0 else (12 if fcf > -capex * 0.1 else 0)
        return _cap(t1 + t2 + t3)

    def spending():
        if rev == 0 or ocf == 0:
            return None
        t1 = (min(ebit / rev, 0.2) / 0.2 if rev > 0 else 0) * 30
        t2 = (min(fcf / ocf, 1) if ocf > 0 else 0) * 30
        t3 = (40 if ocf >= topex else min(ocf / topex, 1) * 40) if topex > 0 else 0
        return _cap(t1 + t2 + t3)

    def surplus():
        if ni == 0 or ocf == 0:
            return None
        t1 = (min(ocf / ni, 2) / 2 if ni != 0 else 0) * 40
        t2 = (30 if fcf > 0 else 0) if ni > 0 else 0
        t3 = 30 if (tca > tcl and ni > 0) else (15 if tca > tcl else 0)
        return _cap(t1 + t2 + t3)

    composite_defs = [
        ("Financial Resilience", resilience(), False, "Can it absorb shocks? Liquidity, solvency, coverage"),
        ("Fragility Under Stress", fragility(), True, "How vulnerable to downturns? Higher = more fragile"),
        ("Ability to Self-Fund Growth", self_fund(), False, "Can it grow without outside capital?"),
        ("Dependence on Outside Capital", dependence(), True, "How reliant on debt/equity raises? Higher = worse"),
        ("Earnings Quality", earnings_quality(), False, "Is profit backed by real cash?"),
        ("Spending Sustainability", spending(), False, "Can current spending continue?"),
        ("Surplus Reality Check", surplus(), False, "Is a surplus real or just timing?"),
    ]
    composites = [{"name": n, "score": s, "inverted": inv,
                   "rating": _rating(s, inv), "what": w} for n, s, inv, w in composite_defs]

    return {"calc": calc, "ratios": ratios, "composites": composites}


def _rating(score, inverted):
    """Scoring key: 70–100 strong, 40–69 moderate, 0–39 weak. Fragility & Dependence are
    inverted (higher = worse)."""
    if score is None:
        return {"emoji": "—", "label": "N/A"}
    if inverted:
        if score < 40:
            return {"emoji": "✅", "label": "Low risk"}
        if score < 70:
            return {"emoji": "⚠️", "label": "Some risk"}
        return {"emoji": "🚩", "label": "High risk"}
    if score >= 70:
        return {"emoji": "✅", "label": "Strong"}
    if score >= 40:
        return {"emoji": "⚠️", "label": "Moderate"}
    return {"emoji": "🚩", "label": "Weak"}


# --- stored periods ---------------------------------------------------------

def list_periods() -> list:
    return [{"id": str(d["_id"]), "period": d.get("period")}
            for d in health_periods.list(order=[("_created_at", "desc")])]


def _period(d: dict) -> dict:
    return {"id": str(d["_id"]), "period": d.get("period"), "inputs": d.get("inputs") or {}}


def get_period(period_id: str | None) -> dict | None:
    if period_id:
        d = health_periods.get(period_id)
        if d:
            return _period(d)
    d = health_periods.one(order=[("_created_at", "desc")])
    return _period(d) if d else None


def save_period(body: dict) -> dict:
    """Upsert a period by name. inputs come keyed by INPUT_KEYS; blanks are omitted."""
    from .values import parse_amount
    from .web import DomainError
    period = (body.get("period") or "").strip()
    if not period:
        raise DomainError("period name is required")
    inputs = {}
    for k in INPUT_KEYS:
        v = parse_amount(body.get(k), k, blank=None)
        if v is not None:
            inputs[k] = v
    existing = health_periods.one({"period": period})
    if existing:
        health_periods.update(existing["_id"], {"inputs": inputs})
        return {"ok": True, "id": existing["_id"]}
    _id = uuid.uuid4().hex
    health_periods.insert({"_id": _id, "period": period, "inputs": inputs})
    return {"ok": True, "id": _id}


def delete_period(body: dict) -> dict:
    from . import registry
    return registry.delete_doc(health_periods, body.get("id"), "period")
