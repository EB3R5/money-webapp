"""Generate docs/schema.mmd from the live SQLite schema (ADR-0012).

Reads sqlite_master and PRAGMA table_info/foreign_key_list from a database initialised with
the current schema files, and writes a Mermaid ER diagram. Run after every schema file:

    .venv/bin/python scripts/schema_doc.py            # writes docs/schema.mmd
    .venv/bin/python scripts/schema_doc.py --check    # exit 1 if docs/schema.mmd is stale
    .venv/bin/python scripts/schema_doc.py --html schema.html   # a review page

Uses a throwaway database under a temp dir, never DATA_DIR."""

import argparse
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.store.database import Database  # noqa: E402
import html as _html  # noqa: E402
import importlib  # noqa: E402
import pkgutil  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "docs" / "schema.mmd"
SKIP = {"schema_version"}


def _mermaid_type(decl: str) -> str:
    return (decl or "TEXT").split("(")[0].upper() or "TEXT"


def render() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        db = Database(Path(tmp) / "data")
        version = db.init()
        lines = ["erDiagram", f"    %% generated by scripts/schema_doc.py from schema version {version}"]
        rels = []
        with db.acquire() as conn:
            for table in db.tables():
                if table in SKIP:
                    continue
                lines.append(f"    {table} {{")
                cur = conn.execute(f'PRAGMA table_info("{table}")')
                for r in cur.fetchall():
                    name = r["name"]
                    key = " PK" if r["pk"] else ""
                    lines.append(f"        {_mermaid_type(r['type'])} {name}{key}")
                lines.append("    }")
                cur = conn.execute(f'PRAGMA foreign_key_list("{table}")')
                for fk in cur.fetchall():
                    rels.append(f"    {fk['table']} ||--o{{ {table} : \"{fk['from']}\"")
        lines.extend(rels)
        return "\n".join(lines) + "\n"


def _stores():
    """table -> Store, for the API-key column of the review page."""
    from app import store as store_pkg
    from app.store.base import Store
    out = {}
    for m in pkgutil.iter_modules(store_pkg.__path__):
        if m.name in ("base", "database"):
            continue
        mod = importlib.import_module(f"app.store.{m.name}")
        for v in vars(mod).values():
            if isinstance(v, Store):
                out[v.table] = v
    return out


def render_html(mermaid: str) -> str:
    """A self-contained review page: one section per table (columns, SQL type, API key,
    kind, PK/FK), the ER diagram rendered by Mermaid from a CDN, and an index."""
    stores = _stores()
    with tempfile.TemporaryDirectory() as tmp:
        db = Database(Path(tmp) / "data")
        version = db.init()
        sections, index = [], []
        with db.acquire() as conn:
            for table in db.tables():
                if table in SKIP:
                    continue
                s = stores.get(table)
                by_col = {}
                if s is not None:
                    by_col = {f.col: f for f in tuple(s.fields)}
                cur = conn.execute(f'PRAGMA foreign_key_list("{table}")')
                fks = {r["from"]: f'{r["table"]}.{r["to"]}' for r in cur.fetchall()}
                cur = conn.execute(f'PRAGMA table_info("{table}")')
                rows = []
                n = 0
                for r in cur.fetchall():
                    n += 1
                    col = r["name"]
                    f = by_col.get(col)
                    if col == "id":
                        api, kind = "_id / id", "id"
                    elif col in ("created_at", "edited_at"):
                        api, kind = "_" + col, "datetime"
                    elif s is not None and s.spill == col:
                        api, kind = "(unmapped keys)", "spill json"
                    elif f is not None:
                        api, kind = f.api, f.kind
                    else:
                        api, kind = "", ""
                    flags = []
                    if r["pk"]:
                        flags.append("PK")
                    if col in fks:
                        flags.append("FK \u2192 " + fks[col])
                    if r["notnull"]:
                        flags.append("NOT NULL")
                    rows.append(
                        "<tr><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>"
                        % (_html.escape(col), _html.escape(r["type"] or "TEXT"),
                           _html.escape(api), _html.escape(kind), _html.escape(", ".join(flags))))
                try:
                    mod_doc = importlib.import_module(f"app.store.{table}").__doc__ or ""
                except ModuleNotFoundError:
                    mod_doc = ""
                index.append(f'<li><a href="#{table}">{table}</a> <span class="muted">{n} cols</span></li>')
                sections.append(
                    f'<section id="{table}"><h2>{table} <span class="muted">{n} columns</span></h2>'
                    + (f'<p class="doc">{_html.escape(mod_doc.strip())}</p>' if mod_doc else "")
                    + '<table><thead><tr><th>column</th><th>SQL type</th><th>API key</th>'
                      '<th>kind</th><th>flags</th></tr></thead><tbody>'
                    + "".join(rows) + "</tbody></table></section>")
    css = """
    body{font:14px/1.5 system-ui,sans-serif;margin:0;padding:24px 32px;color:#1c1c1c;background:#fafafa}
    h1{font-size:22px;margin:0 0 4px} h2{font-size:17px;margin:32px 0 6px;border-bottom:1px solid #ddd;padding-bottom:4px}
    .muted{color:#777;font-weight:normal;font-size:12px} .doc{color:#444;margin:0 0 8px;max-width:80ch;white-space:pre-line}
    table{border-collapse:collapse;min-width:640px} th,td{text-align:left;padding:3px 10px;border-bottom:1px solid #eee;vertical-align:top}
    th{font-size:12px;color:#555;background:#f0f0f0} code{font-size:13px}
    nav ul{columns:3;list-style:none;padding:0;margin:8px 0 0} nav li{margin:0 0 2px}
    .legend{color:#555;font-size:13px;max-width:90ch} pre.mermaid{background:#fff;padding:12px;overflow:auto;border:1px solid #ddd}
    """
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>money-webapp schema</title>
<style>{css}</style>
<script type="module">
import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs";
mermaid.initialize({{startOnLoad:true, maxTextSize: 200000, er: {{useMaxWidth: false}}}});
</script></head><body>
<h1>money-webapp SQLite schema <span class="muted">version {version}, generated by scripts/schema_doc.py</span></h1>
<p class="legend"><b>API key</b> is the spreadsheet-style name the app and JS islands use for the column (ADR-0012 field maps);
<b>kind</b> is the store's typing: text, real, int, bool, date, datetime, json. A <i>spill json</i> column receives any API key
the store does not map (open-ended registries and config docs). Dates and timestamps are ISO-8601 text.</p>
<nav><ul>{"".join(index)}</ul></nav>
<h2>ER diagram</h2>
<pre class="mermaid">{_html.escape(mermaid)}</pre>
{"".join(sections)}
</body></html>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if docs/schema.mmd is stale")
    ap.add_argument("--html", metavar="PATH", help="also write a self-contained HTML review page")
    args = ap.parse_args()
    text = render()
    if args.html:
        out = Path(args.html).expanduser()
        out.write_text(render_html(text))
        print(f"wrote {out}")
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale; run scripts/schema_doc.py", file=sys.stderr)
            return 1
        print("schema.mmd is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
