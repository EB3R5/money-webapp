"""Financial Health Analysis — ratio scores for one period of manual inputs. You enter one
period of balance-sheet / income-statement / cash-flow inputs and it computes the six ratio
categories plus seven composite 0–100 scores (formulas carried over from the household's
earlier spreadsheet tooling; composites cap at 100 but can go negative).

Inputs are stored per named period in `health_periods`; everything else is computed live by
compute(), a pure function (no DB) so the math is unit-testable directly.
"""

import uuid

from .store.health_periods import health_periods

